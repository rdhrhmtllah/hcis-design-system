// Regenerates the Evo HCIS icon runtime from the official Lucide package.
// Usage:  node tools/build-lucide-icons.mjs <path-to-extracted lucide-static/package>
// Get the package:  https://registry.npmjs.org/lucide-static/latest  -> dist.tarball (tar -xzf)
// Writes: build/icons.js, build/lucide-tags.js, assets/icons/*.svg, assets/icons/sprite.svg, assets/icons/LICENSE
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = process.argv[2];
if (!pkg || !fs.existsSync(path.join(pkg, 'icon-nodes.json'))) {
  console.error('Pass the extracted lucide-static "package" folder.');
  process.exit(1);
}
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
const nodes = JSON.parse(fs.readFileSync(path.join(pkg, 'icon-nodes.json'), 'utf8'));
const tags = JSON.parse(fs.readFileSync(path.join(pkg, 'tags.json'), 'utf8'));

const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const serialize = (list) => list.map(([tag, attrs]) =>
  '<' + tag + Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => ' ' + k + '="' + esc(v) + '"').join('') + '/>').join('');

const BODY = {};
for (const name of Object.keys(nodes).sort()) BODY[name] = serialize(nodes[name]);

// Official Lucide aliases (renamed / deprecated names still shipped as SVG files) -> canonical name.
const norm = (s) => s.replace(/<!--[\s\S]*?-->/g, '').replace(/<svg[\s\S]*?>/, '').replace(/<\/svg>/, '').replace(/\s+/g, '').replace(/\/>/g, '>');
const byBody = new Map();
for (const name of Object.keys(nodes)) {
  const f = path.join(pkg, 'icons', name + '.svg');
  if (fs.existsSync(f)) byBody.set(norm(fs.readFileSync(f, 'utf8')), name);
}
const ALIASES = {};
for (const file of fs.readdirSync(path.join(pkg, 'icons'))) {
  const name = file.replace(/\.svg$/, '');
  if (nodes[name]) continue;
  const canon = byBody.get(norm(fs.readFileSync(path.join(pkg, 'icons', file), 'utf8')));
  if (canon) ALIASES[name] = canon;
}

// Evo HCIS legacy names (custom set retired) -> Lucide, with the default size each slot used.
const LEGACY = {
  'home': ['house', 22], 'user': ['user', 22], 'grid': ['layout-grid', 22],
  'check': ['check', 12], 'close': ['x', 18], 'plus': ['plus', 22],
  'chevron-right': ['chevron-right', 16], 'chevron-left': ['chevron-left', 20], 'chevron-down': ['chevron-down', 16],
  'arrow-right': ['arrow-right', 20], 'arrow-left': ['arrow-left', 20], 'swap': ['arrow-left-right', 18],
  'search': ['search', 20], 'refresh': ['refresh-cw', 22], 'retry': ['rotate-cw', 15], 'rotate-ccw': ['rotate-ccw', 20],
  'history': ['history', 26], 'clock': ['clock', 20],
  'calendar': ['calendar', 22], 'calendar-days': ['calendar-days', 26], 'calendar-check': ['calendar-check', 18], 'calendar-x': ['calendar-x', 22],
  'document': ['file', 20], 'document-lines': ['file-text', 26], 'video': ['video', 20], 'folder': ['folder', 22],
  'id-card': ['id-card', 22], 'bar-chart': ['chart-column', 22], 'trend': ['chart-line', 20],
  'graduation': ['graduation-cap', 22], 'user-check': ['user-check', 16], 'activity': ['square-activity', 18],
  'bell': ['bell', 18], 'help': ['circle-question-mark', 18], 'info': ['info', 20],
  'alert': ['circle-exclamation-point', 18], 'warning': ['triangle-exclamation-point', 22], 'alert-circle': ['circle-exclamation-point', 22],
  'wifi-off': ['wifi-off', 20], 'ban': ['ban', 20], 'wallet': ['wallet', 20], 'banknote': ['banknote', 20],
  'heart': ['heart', 20], 'trash': ['trash', 18], 'download': ['download', 15], 'upload': ['upload', 20],
  'logout': ['log-out', 22], 'play': ['play', 16], 'route': ['route', 22], 'chat': ['message-square', 18],
  'phone': ['phone', 18], 'mail': ['mail', 18]
};
const resolve = (n) => (BODY[n] ? n : ALIASES[n]);
for (const [old, [luc]] of Object.entries(LEGACY)) {
  if (!resolve(luc)) { console.error('Legacy map points to missing Lucide icon: ' + old + ' -> ' + luc); process.exit(1); }
  LEGACY[old][0] = resolve(luc);
}

const runtime = `/* Evo HCIS Mobile icon runtime: Lucide v${version} (ISC, https://lucide.dev). GENERATED by tools/build-lucide-icons.mjs; do not hand-edit.
 * Every icon in the product comes from Lucide. Custom-drawn or mixed icon sets are not allowed (DESIGN.md section 9).
 * Usage (browser):  <script src="build/icons.js"></script>
 *   evIcon('calendar-check')                     -> SVG string, 24px, stroke 2
 *   evIcon('check', { size: 16, label: 'Selesai' })
 *   evHydrateIcons(root)                         -> replaces <i data-ev-icon="name" data-size="20"></i>
 *   evHasIcon(name), evIconNames(), evResolveIcon(name)
 * Names: any Lucide name (https://lucide.dev/icons), any official Lucide alias, or a retired Evo name (EV_ICON_LEGACY). */
(function (g) {
  var VERSION = ${JSON.stringify(version)};
  var ICONS = ${JSON.stringify(BODY)};
  var ALIASES = ${JSON.stringify(ALIASES)};
  var LEGACY = ${JSON.stringify(Object.fromEntries(Object.entries(LEGACY).map(([k, [n, s]]) => [k, { lucide: n, size: s }])))};
  var DEFAULT_SIZE = 24, DEFAULT_STROKE = 2, MIN_STROKE = 1.5, MAX_STROKE = 2.5;
  function evResolveIcon(name) {
    if (ICONS[name]) { return name; }
    if (LEGACY[name]) { return LEGACY[name].lucide; }
    if (ALIASES[name]) { return ALIASES[name]; }
    return null;
  }
  function evIcon(name, o) {
    o = o || {};
    var key = evResolveIcon(name);
    if (!key) { throw new Error('Unknown Lucide icon: ' + name + ' (see https://lucide.dev/icons)'); }
    var s = o.size || (LEGACY[name] ? LEGACY[name].size : DEFAULT_SIZE);
    var w = o.stroke ? Math.min(MAX_STROKE, Math.max(MIN_STROKE, o.stroke)) : DEFAULT_STROKE;
    var a11y = o.label ? ' role="img" aria-label="' + String(o.label).replace(/"/g, '&quot;') + '"' : ' aria-hidden="true" focusable="false"';
    return '<svg class="ev-icon lucide lucide-' + key + '" width="' + s + '" height="' + s + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + w + '" stroke-linecap="round" stroke-linejoin="round"' + a11y + '>' + ICONS[key] + '</svg>';
  }
  function evHydrateIcons(root) {
    (root || document).querySelectorAll('[data-ev-icon]').forEach(function (el) {
      var size = el.getAttribute('data-size'), stroke = el.getAttribute('data-stroke');
      el.outerHTML = evIcon(el.getAttribute('data-ev-icon'), { size: size ? +size : 0, stroke: stroke ? +stroke : 0, label: el.getAttribute('aria-label') });
    });
  }
  function evHasIcon(name) { return !!evResolveIcon(name); }
  function evIconNames() { return Object.keys(ICONS); }
  g.EV_ICONS = ICONS; g.EV_ICON_ALIASES = ALIASES; g.EV_ICON_LEGACY = LEGACY; g.EV_LUCIDE_VERSION = VERSION;
  g.evIcon = evIcon; g.evHydrateIcons = evHydrateIcons; g.evHasIcon = evHasIcon; g.evIconNames = evIconNames; g.evResolveIcon = evResolveIcon;
  if (typeof module !== 'undefined') { module.exports = { ICONS: ICONS, ALIASES: ALIASES, LEGACY: LEGACY, VERSION: VERSION, evIcon: evIcon, evResolveIcon: evResolveIcon }; }
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(root, 'build', 'icons.js'), runtime);

const tagOut = {};
for (const name of Object.keys(BODY)) tagOut[name] = (tags[name] || []).join(' ');
fs.writeFileSync(path.join(root, 'build', 'lucide-tags.js'),
  `/* Lucide v${version} search tags (ISC). GENERATED by tools/build-lucide-icons.mjs. Used by preview/icons.html only. */\nwindow.EV_LUCIDE_TAGS = ${JSON.stringify(tagOut)};\n`);

const iconsDir = path.join(root, 'assets', 'icons');
fs.mkdirSync(iconsDir, { recursive: true });
for (const f of fs.readdirSync(iconsDir)) fs.rmSync(path.join(iconsDir, f), { recursive: true, force: true });
for (const name of Object.keys(BODY)) fs.copyFileSync(path.join(pkg, 'icons', name + '.svg'), path.join(iconsDir, name + '.svg'));
fs.copyFileSync(path.join(pkg, 'sprite.svg'), path.join(iconsDir, 'sprite.svg'));
fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(iconsDir, 'LICENSE'));

console.log(JSON.stringify({ version, icons: Object.keys(BODY).length, aliases: Object.keys(ALIASES).length, legacy: Object.keys(LEGACY).length }));
